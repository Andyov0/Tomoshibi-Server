/**
 * Where the code running this can be read.
 *
 * An obligation rather than a courtesy, and one that only a page can discharge.
 * This is licensed under the AGPL, whose thirteenth section says that offering
 * people the use of a program over a network obliges the operator to offer them
 * its source — and everybody being offered the use of this one arrives here.
 *
 * The address comes from the server because a deployment running a changed copy
 * owes its visitors that copy rather than this one. Where a server says nothing,
 * nothing is drawn: an offer of somebody else's source is worse than none, since
 * it looks discharged.
 */
function Source() {
	const [source, setSource] = useState("");

	useEffect(() => {
		let live = true;

		void deployment().then((said) => {
			if (live) setSource(said.source);
		});

		return () => {
			live = false;
		};
	}, []);

	if (!source) return null;

	return (
		<a
			href={source}
			target="_blank"
			rel="noreferrer"
			className="absolute inset-x-0 bottom-3 text-center text-[11px] text-fg-muted/60 transition-colors hover:text-fg-muted"
		>
			{/* Not translated, and not an oversight. It is the name of the licence
			    this is under, which is the same string in every language, and the
			    word beside it is what the link goes to. */}
			AGPL-3.0 · source
		</a>
	);
}

function Form({ room, onRoomChange, onJoin, guest = false, invitation, as, onBack, arranged }: PreJoinProps) {
	// Whether the door turned this person away for wanting an invitation, which
	// is the one refusal there is something to do about from this screen.
	const [refused, setRefused] = useState(false);

	const t = useT();
	const [name, setName] = useState(() => recall(NAME_KEY) ?? "");
	const [secret, setSecret] = useState(() => recall(PASSPHRASE_KEY) ?? "");
	const [devices, setDevices] = useState(rememberedDevices);
	const [track, setTrack] = useState<LocalVideoTrack>();

	// Whether the preview is blurred, and whether it is busy becoming so. The
	// first press loads two and a half megabytes of runtime and model, which on
	// a slow line is several seconds of a button that has to look like it is
	// doing something.
	const [blurring, setBlurring] = useState(false);
	const [blurLoading, setBlurLoading] = useState(false);

	const toggleBlur = async () => {
		const made = current.current;
		if (!made) return;

		const wants = !blurring;

		setBlurLoading(true);

		try {
			const now = await blur(made, wants);

			// What happened rather than what was asked for. A model that would
			// not load leaves the switch off, which is the truth about the
			// picture being sent.
			setBlurring(now);
			rememberBlur(now);
		} finally {
			setBlurLoading(false);
		}
	};
	const [joining, setJoining] = useState(false);

	// Empty means whichever measures fastest, which is what nearly everybody
	// wants and what nobody should have to choose. What is not empty is what
	// somebody already chose — in the lobby, a screen ago — and this used to
	// start blank regardless, so a machine picked deliberately came back as
	// "whichever is fastest" on the very next page.
	const [sealWord, setSealWord] = useState("");
	const [relay, setRelay] = useState(() => as?.relay ?? chosenRelay());
	const [servers, setServers] = useState<OfferedRelay[]>([]);
	const [offerChoice, setOfferChoice] = useState(false);

	/*
	 * What the password manager was last offered, so it is not offered again.
	 *
	 * Storing a credential is a prompt: Chromium asks whether to save it, every
	 * time, and it asks whether or not it already holds exactly that pair. The
	 * passphrase field is filled from storage on load, so somebody who joins a
	 * room, leaves, and joins another is answering the same question about the
	 * same secret on every join. Enough of those and the answer stops being read.
	 *
	 * Seeded with what the page opened holding, which is the whole trick: a
	 * passphrase restored from the last visit has been offered before, and one
	 * that differs from it is the only thing worth offering now. A person who
	 * changes their passphrase is asked once, at the moment they changed it.
	 *
	 * A ref rather than state because nothing on screen depends on it, and it
	 * must survive the re-render that a join causes.
	 */
	const offered = useRef(`${recall(NAME_KEY) ?? ""}\u0000${recall(PASSPHRASE_KEY) ?? ""}`);

	// Held in a ref as well, so the cleanup below stops whatever is current
	// rather than whatever was current when the effect last ran.
	const current = useRef<LocalVideoTrack>();

	useEffect(() => {
		let live = true;

		if (!devices.camera) {
			current.current?.stop();
			current.current = undefined;
			setTrack(undefined);
			return;
		}

		// The camera last picked in a call, where it is still plugged in. The
		// room asks for the same one when it starts (preferences.ts), and a
		// preview of another camera would be a rehearsal of the wrong picture.
		usableDeviceChoice()
			.then((usable) => createLocalVideoTrack(usable.videoinput ? { deviceId: usable.videoinput } : undefined))
			.then((made) => {
				if (!live) {
					made.stop();
					return;
				}
				current.current = made;
				setTrack(made);

				// Where this browser asked for it last time. The preview is the
				// only chance somebody gets to check what the room will see
				// before the room sees it, so a preview that ignores the setting
				// is a preview of the wrong thing.
				if (blurWanted() && blurPossible()) {
					setBlurLoading(true);
					void blur(made, true)
						.then((worked) => live && setBlurring(worked))
						.finally(() => live && setBlurLoading(false));
				}
			})
			.catch(() => {
				// A refused camera is an answer. The switch falls back to off so
				// the preview and the control agree.
				if (live) setDevices((held) => ({ ...held, camera: false }));
			});

		return () => {
			live = false;
		};
	}, [devices.camera]);

	// Asked once. The list changes when a machine is brought up or taken away,
	// which is not a thing that happens while somebody is looking at a join
	// screen — and asking again on a timer would be a request per visitor per
	// minute for an answer that does not move.
	useEffect(() => {
		let live = true;

		void relays().then((offered) => {
			if (!live) return;

			setServers(offered.relays);

			// Only where there is a choice to make. One relay is not a choice,
			// and a deployment that will not act on a preference would be
			// offering a control that does nothing.
			setOfferChoice(offered.measure && offered.relays.length > 1);
		});

		return () => {
			live = false;
		};
	}, []);

	// Stopped only when the screen goes away for good. The track itself is handed
	// to the room on join, so tearing it down on every render would drop the
	// preview and prompt again a moment later.
	useEffect(() => () => current.current?.stop(), []);

	/*
	 * Two ways in, and one of them is not drawn.
	 *
	 * The field below is the one this teaches, because a field is the only shape
	 * a password manager can see — the whole reason nobody could remember their
	 * passphrase is that it used to be the half of this one after a hash, which
	 * is invisible to every manager ever written.
	 *
	 * `Alice#secret` still works, and goes on working without being advertised.
	 * It is the form this application taught everybody who has used it, and a
	 * syntax that quietly stops being accepted is worse than one that is no
	 * longer mentioned. The field wins where both are filled, since it is the
	 * one somebody can see.
	 */
	const { name: typedName, passphrase: written } = parseName(name);

	// The name a link was made for, which is the name this guest will wear.
	const locked = guest ? invitation?.name : undefined;

	/*
	 * A guest of a room held under a scope, who is a guest whatever else they
	 * bring: the server mints them an issued mark and ignores a passphrase. So
	 * none is sent, and nothing about the one this browser has kept is touched —
	 * a guest join used to write over it with nothing, and offer the password
	 * manager a pair made of the link's name and somebody's own secret.
	 */
	const scopedGuest = guest && scopeOf(room) !== "";

	// Whoever is signed in, where somebody is. Their name is already theirs and
	// their signature comes from the session, so nothing is typed and nothing is
	// sent — a passphrase in the request would be a second answer to a question
	// already settled, and the one that wins would be whichever the server read
	// first.
	const display = as ? as.name : locked || typedName;
	const passphrase = as || scopedGuest ? "" : secret || written;

	/*
	 * Whether the server is chosen here, which is everywhere but the device
	 * screen after the lobby: that one was chosen a screen ago, and the lobby's
	 * choice is what is sent.
	 *
	 * Including a meeting link opened by somebody signed in, which hid the
	 * picker for as long as `as` alone decided it. The reasoning written beside
	 * it was that the server places an arranged meeting where it was arranged
	 * whatever is sent, and that was half of it: the meeting is held there, but
	 * the machine somebody dials is still the one they choose, and the call is
	 * forwarded from it to the one holding the meeting (internal/app/app.go,
	 * arrangedPlacement and the forwarding after it). So anybody signed in on a
	 * meeting link, its host included, had no way to choose the door they came
	 * in by, and went through whatever this tab last remembered.
	 */
	const picks = !as || arranged !== undefined;

	const submit = async () => {
		if (!display || joining) return;

		// Not a name somebody else chose for them. It is this link's, and
		// keeping it would greet them by it on every visit after.
		if (!locked) keep(NAME_KEY, display);
		rememberDevices(devices);

		// Whatever was last joined with, which means clearing the field and
		// joining is how somebody takes it back off this machine — except as a
		// scoped room's guest, who joined with nothing on purpose.
		if (!scopedGuest) {
			if (passphrase) keep(PASSPHRASE_KEY, passphrase);
			else keep(PASSPHRASE_KEY, undefined);
		}

		// And offered to the password manager, which keeps it better than this
		// can and carries it to the same person's other devices. Once, for any
		// given pair: the offer is a prompt, and one that arrives on every join
		// to ask about a secret the browser already holds is one nobody reads.
		const pair = `${display}\u0000${passphrase}`;
		if (passphrase && pair !== offered.current) {
			offered.current = pair;
			void remember(display, passphrase);
		}

		setJoining(true);

		try {
			await onJoin({
				name: display,
				passphrase,
				secret: sealWord,
				relay: picks ? relay : (as?.relay ?? relay),
				...devices,
			});
		} catch (whatever) {
			// Reported by whoever tried, which holds the room object that has to
			// be torn down and the words for what went wrong. Caught here all the
			// same, because a rejection nobody catches is a red line in a console
			// and nothing at all on the screen.
			//
			// One of them is answered here rather than only reported: a door that
			// asks for an invitation is a door somebody can knock on, and the
			// moment they were turned away is the moment that is worth offering.
			// Matched on the code rather than the sentence, which is translated.
			//
			// A room held under a scope is the same door with a different
			// sentence: its members answer a knock as a host would.
			if (whatever instanceof Refused && (whatever.reason === "not_invited" || whatever.reason === "not_in_scope")) {
				setRefused(true);
			}
		} finally {
			/*
			 * Put back whether it worked or not, which it was not doing at all.
			 * A join that was refused — a room only administrators may open, a
			 * name the server would not have — left the button reading "Joining"
			 * for ever, with a notice beside it saying why and no way to act on
			 * it. The only way out of this screen was to reload it.
			 *
			 * On success this runs into a screen that has already been replaced,
			 * which costs nothing: the room is mounted by then and nobody is
			 * looking at this button.
			 */
			setJoining(false);
		}
	};

	return (
		<Page>
			{/*
			 * Two columns where the screen is wider than it is tall and there is
			 * room for both, one column otherwise, the picture always first.
			 *
			 * Keyed to the shape of the viewport and not only its width, because
			 * the arrangement this replaces is worst on a screen that is wide and
			 * short — a phone turned on its side, or a window dragged flat. There
			 * a stacked picture is taller than the screen it is on, and the reader
			 * scrolls past their own face to reach the button.
			 */}
			<div className="flex w-full max-w-6xl flex-col gap-6 md:landscape:flex-row md:landscape:items-stretch md:landscape:gap-8">
				<div className="md:landscape:flex-[1.35]">
					<SelfView track={track}>
						{/*
						 * The same island the call puts these two switches in, in
						 * the same place, so this screen is a rehearsal of the room
						 * rather than a different room.
						 */}
						<div className="-translate-x-1/2 absolute bottom-3 left-1/2 flex items-center gap-1.5 rounded-full border border-border bg-surface/90 p-1.5 shadow-2xl backdrop-blur-md">
							<Button
								variant={devices.microphone ? "secondary" : "danger"}
								size="round"
								className="size-9"
								aria-label={devices.microphone ? t("Mute microphone") : t("Unmute microphone")}
								aria-pressed={devices.microphone}
								onClick={() => setDevices((held) => ({ ...held, microphone: !held.microphone }))}
							>
								{devices.microphone ? <Mic /> : <MicOff />}
							</Button>

							<Button
								variant={devices.camera ? "secondary" : "danger"}
								size="round"
								className="size-9"
								aria-label={devices.camera ? t("Turn camera off") : t("Turn camera on")}
								aria-pressed={devices.camera}
								onClick={() => setDevices((held) => ({ ...held, camera: !held.camera }))}
							>
								{devices.camera ? <Video /> : <VideoOff />}
							</Button>

							{/* Third, and only where the browser can do it. A
							    switch that says a browser cannot blur is a switch
							    somebody presses and reads an apology from. */}
							{blurPossible() && (
								<Button
									variant={blurring ? "secondary" : "ghost"}
									size="round"
									className="size-9"
									disabled={!devices.camera || blurLoading}
									aria-label={blurring ? t("Show my background") : t("Blur my background")}
									aria-pressed={blurring}
									onClick={() => void toggleBlur()}
								>
									{blurLoading ? <Loader2 className="animate-spin" /> : <Sparkles />}
								</Button>
							)}
						</div>
					</SelfView>

					{/*
					 * Under the picture rather than inside it, because it answers a
					 * different question from the switch above it. The switch says
					 * whether the microphone will be on; this says whether it works,
					 * which nothing on this screen said until now — and this screen
					 * exists to answer exactly those two things about the two
					 * devices, which is what the comment beside the form says it is
					 * for.
					 */}
					<div className="mt-2.5 px-1">
						<MicLevel on={devices.microphone} />
					</div>
				</div>

				<form
					className="flex flex-col justify-center gap-5 md:landscape:min-w-[17rem] md:landscape:flex-1"
					onSubmit={(event) => {
						event.preventDefault();
						void submit();
					}}
				>
					{/*
					 * Everything above the button belongs to somebody who has not
					 * answered these questions yet.
					 *
					 * Somebody signed in has answered all of them: their name at the
					 * sign-in, the room and the machine in the lobby. What was left
					 * on this screen was a room code to confirm, a name to type, a
					 * passphrase to type, and a server to pick — four answers to
					 * questions already settled, between them and a meeting they had
					 * already said they wanted to be in.
					 *
					 * So for them this page is the one thing nobody can answer in
					 * advance: whether the camera is pointing at the right thing and
					 * whether the microphone is the right one.
					 */}
					{/*
					 * The name, always, and editable only where it is still a
					 * question.
					 *
					 * Taking it away entirely left a button alone in half a screen,
					 * which reads as a page that failed to load the rest of itself —
					 * and it took with it the one thing this screen is for
					 * confirming: that the meeting somebody is about to walk into is
					 * the one they meant. It is not a field for somebody who came
					 * through the lobby, because they typed it there; it is a
					 * heading, which is what it always was underneath.
					 */}
					{as ? (
						<div className="flex flex-col gap-2">
							{/*
							 * The way back, because this screen is a step and not a
							 * destination. Somebody who came through the lobby and
							 * changed their mind about which meeting they wanted had
							 * nothing to press: the only exits were joining a call
							 * they did not want and the browser's back button.
							 */}
							<button
								type="button"
								onClick={onBack}
								className={cn(
									"flex w-fit items-center gap-1.5 rounded-md px-1.5 py-1 -ml-1.5",
									"text-[12px] text-fg-muted transition-colors hover:bg-surface-hi hover:text-fg",
								)}
							>
								<ArrowLeft className="size-3.5" />
								{t("Back")}
							</button>

							<h1 className="readout truncate font-semibold text-fg text-xl tracking-tight">
								{room}
							</h1>
						</div>
					) : (
						<RoomTitle
							room={room}
							onChange={onRoomChange}
							fixed={guest || arranged !== undefined}
							invited={guest || arranged !== undefined}
						/>
					)}

					{/*
					 * Nothing to fill in for somebody signed in.
					 *
					 * Their name is already theirs and their signature comes from
					 * the session, so both fields were asking for answers that had
					 * already been given — and one of them was asking for a
					 * passphrase on a screen they reach after having typed it. What
					 * is left is the half of this page that is about devices, which
					 * is the half nobody can answer in advance.
					 */}
					{!as && (
						<div className="flex flex-col gap-2">
							<Identity
								name={locked ?? name}
								passphrase={secret}
								onName={setName}
								onPassphrase={setSecret}
								nameOnly={guest}
								fixed={locked !== undefined}
							/>

							{/* One line, which changes rather than doubling: what a
							    passphrase is for until there is one, and what it did
							    once there is. */}
							<p className="text-fg-muted text-xs leading-snug">
								{locked
									? t("You were invited to this room as {name}.", { name: locked })
									: guest
										? t("You were invited to this room. Choose a name and go in.")
										: passphrase
											? t("Only you can join as {name}", { name: display || "?" })
											: t("Add a passphrase to keep your name, and to run the room you open.")}
							</p>

							{/* When the link stops working, where it does. Said once,
							    here, because a guest who arrives early for a call at
							    four should know the link will still be good at four;
							    and in their own clock, since whoever sent it may not
							    share it. A link with no end says nothing. */}
							{guest && invitation?.until && (
								<p className="text-fg-muted text-xs leading-snug">
									{invitation.from
										? t("This link works from {from} until {until}.", {
												from: whenSaid(invitation.from),
												until: whenSaid(invitation.until),
											})
										: t("This link works until {until}.", { until: whenSaid(invitation.until) })}
								</p>
							)}
						</div>
					)}

					{/* Folded away, under the identity, because most calls do not
					    want it and the ones that do want it before they start.
					    Offered to a guest as much as to anybody: the word is not
					    the passphrase and knowing it is what the invitation
					    assumes. */}
					<Sealed value={sealWord} onChange={setSealWord} />

					{/* Below the identity and above the button, because it is the
					    last thing anybody would change and the first thing nobody
					    should have to. Absent entirely where there is nothing to
					    choose between. */}
					{offerChoice && picks && (
						<ServerPicker
							relays={servers}
							value={relay}
							onChange={(chosen) => {
								setRelay(chosen);

								// Written down here as well as in the lobby.
								// Only the lobby was remembering, so a change
								// made on this screen survived exactly until
								// the page was reloaded.
								rememberRelay(chosen);
							}}
						/>
					)}

					{/* On a meeting link the button waits for the meeting, and the
					    join happens when it begins — carrying the invitation the meeting
					    produced, through the same path an admission from the waiting room
					    takes. See Waiting for why nothing is asked until this is pressed. */}
					{arranged ? (
						<Waiting
							token={arranged.token}
							name={display}
							onArranged={(said) => {
								// The room is what the server says it is, not what the hash says.
								if (said.room && said.room !== room) onRoomChange(said.room);
							}}
							onGo={(invite) => {
								keepInvite(invite);
								setRefused(false);
								void submit();
							}}
							onStart={() => void submit()}
						/>
					) : (
						<Button type="submit" variant="primary" size="lg" className="w-full" disabled={!display || joining}>
							{joining ? t("Joining…") : t("Join")}
						</Button>
					)}

					{/* Only after the door has said so. Most people pressing Join
					    have a link and never see this; somebody who was turned
					    away is exactly who it is for, and at that moment it is the
					    only thing on the screen worth pressing. */}
					{refused && (
						<Knocking
							room={room}
							name={display}
							onAdmitted={(invite) => {
								// Straight in, carrying the invite the answer produced.
								// There is one way through this door and this is being
								// handed it, rather than a second.
								//
								// Kept and re-submitted rather than written into the
								// address bar and reloaded. The reload worked and was
								// wrong: it threw away the name, the devices and the
								// sealing word, and put somebody who had waited two
								// minutes back on the form they filled in to press Join
								// a second time. Everything the join needs is already on
								// this screen; only the token was missing.
								keepInvite(invite);
								setRefused(false);
								void submit();
							}}
						/>
					)}
				</form>
			</div>
		</Page>
	);
}

/**
 * Why this page cannot open a camera.
 *
 * A dead end rather than a warning, because there is nothing to try: the page
 * has to be loaded from somewhere else before any of this works.
 */
function Unavailable({ reason }: { reason: string }) {
	const t = useT();

	return (
		<Page>
			<div className="w-full max-w-md space-y-4 text-center">
				<ShieldAlert className="mx-auto size-10 text-fg-muted" />
				<h1 className="font-semibold text-2xl tracking-tight">{t("Can't use your camera or microphone")}</h1>
				<p className="text-fg-muted text-sm">{reason}</p>
			</div>
		</Page>
	);
}

/**
 * The name last joined under, for a reload that is going straight back in.
 *
 * Whatever was typed, including anything after a hash: the passphrase half is
 * dropped on the way out, because a rejoin carries the identity it already has
 * and does not need to prove the name again.
 */
export function rememberedName(): string {
	return parseName(recall(NAME_KEY) ?? "").name;
}
